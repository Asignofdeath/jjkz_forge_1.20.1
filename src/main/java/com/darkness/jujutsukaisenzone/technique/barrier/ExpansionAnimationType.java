package com.darkness.jujutsukaisenzone.technique.barrier;

/**
 * 结界展开动画类型枚举。
 * <p>
 * 定义结界展开时的动画效果，不同结界类型有不同的展开方式。
 */
public enum ExpansionAnimationType
{
    /**
     * 从下向上包围。
     * <p>
     * 普通结界术使用此动画，结界方块从最低层开始逐层向上放置，
     * 像从地面升起一样包围目标区域。
     * <p>
     * 排序方式：按 Y 坐标升序，Y 坐标相同的按到中心的水平距离升序。
     */
    BOTTOM_UP,

    /**
     * 从施术者背后向前方包围。
     * <p>
     * 领域展开使用此动画，结界方块从施术者背后开始向前方逐层放置，
     * 像从身后展开一样包围目标区域。
     * <p>
     * 排序方式：按到玩家背后参考点的距离升序。
     */
    BACK_TO_FRONT,

    /**
     * 从中心向外扩散。
     * <p>
     * 预留动画类型，按到中心的距离升序放置。
     */
    CENTER_OUT,

    /**
     * 无动画，即时放置。
     * <p>
     * 小半径结界或不需要动画效果时使用。
     */
    INSTANT
}
